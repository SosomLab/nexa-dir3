/// 이름에 분해(결합) 문자가 있는가 = "NFD" 식별: 조합형 한글 자모(U+1100~U+11FF) 또는 결합 기호(U+0300~U+036F).
pub fn is_decomposed(s: &str) -> bool {
    s.chars()
        .any(|c| matches!(c, '\u{1100}'..='\u{11FF}' | '\u{0300}'..='\u{036F}'))
}

