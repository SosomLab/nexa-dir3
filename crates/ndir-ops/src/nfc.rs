/// 1단계 결과에 같은 규칙 1회 더(2단계 · 더 깊은 단계 없음) · Python `unicodedata` 13.0(scratch `gen_nfc_latin.py` · 10-25). (글자, 기호) 정렬 → 이진 탐색.
/// 없는 조합 = None(그대로 둔다).
fn latin(base: char, mark: char) -> Option<char> {
    LATIN
        .binary_search_by(|(b, m, _)| (*b, *m).cmp(&(base, mark)))
        .ok()
        .map(|i| LATIN[i].2)
}

